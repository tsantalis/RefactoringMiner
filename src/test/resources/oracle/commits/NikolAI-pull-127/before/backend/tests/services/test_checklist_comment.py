"""Tests for the checklist in NikolAI's review comment (US-9)."""

# AI contribution: 50%

from datetime import UTC, datetime
from uuid import UUID

import pytest

from app.agents.base import AgentResult, PullRequestRef
from app.db.models.checklist import Checklist, CommentChecklist
from app.db.models.feedback import Finding, FindingLocation
from app.github.comments import MAX_COMMENT_CHARS
from app.services.review_comment import COMMENT_MARKER, render_comment

PR_REF = PullRequestRef(repository="octocat/demo", number=7, author="student1")
PR_URL = "https://github.com/octocat/demo/pull/7"
# sha256 of "src/db.py", "a.py" and "src/[x](y).py", computed with sha256sum.
DB_PY = "6045026f204d0e038fb8eaf86675588c01bd88d1b0afcbd9d26221b7f692e500"
A_PY = "f0de093a8c24f6a3ed1c71a2eedb8d29cb68daa281b1dd2323b67d75ce3fb800"
ODD_PY = "858b90e157006d14a4b500c2578f0d8d541d6478d2ba362c2dbf424c33ddc7c1"
FINDING_ID = "00000000-0000-4000-8000-000000000001"
FOOTER = (
    "<sub>AI-generated by NikolAI · test-model · 1.2 s · advisory feedback, not a grade · "
    f"[Open in the NikolAI tab]({PR_URL}#nikolai/checklist)</sub>"
)


def review(content: str = "The title is clear.") -> AgentResult:
    return AgentResult(
        agent="stub",
        prompt_version="stub-v1",
        model="test-model",
        provider="Cohere",
        generation_id="gen-1",
        content=content,
        finish_reason="stop",
        latency_ms=1234.0,
        usage=None,
        pull_request=PR_REF,
        created_at=datetime.now(UTC),
    )


def location(path: str, start: int | None, end: int | None = None) -> FindingLocation:
    return FindingLocation(file_path=path, side="child", start_line=start, end_line=end)


def item(
    name: str = "Unclear name",
    *locations: FindingLocation,
    description: str | None = "Rename y.",
    severity: str | None = "medium",
    category: str | None = "maintainability",
    finding_id: str = FINDING_ID,
) -> Finding:
    return Finding.model_validate(
        {
            "id": UUID(finding_id),
            "name": name,
            "description": description,
            "severity": severity,
            "category": category,
            "locations": list(locations or (location("a.py", 1),)),
        }
    )


def comment(
    *findings: Finding,
    withheld: int = 0,
    failed_since: bool = False,
    nothing_reviewed: bool = False,
) -> str:
    checklist = Checklist(
        findings=list(findings), withheld_count=withheld, nothing_reviewed=nothing_reviewed
    )
    return render_comment(
        review(), PR_REF, CommentChecklist(checklist=checklist, failed_since=failed_since)
    )


def test_each_finding_is_an_unticked_item_with_its_severity_category_and_line_links() -> None:
    sql = item(
        "SQL built from input",
        location("src/db.py", 12),
        location("src/db.py", 40, 42),
        description="Use a parameterized query.",
        severity="high",
        finding_id="00000000-0000-4000-8000-0000000000aa",
    )

    assert comment(sql, item(), withheld=3) == (
        f"{COMMENT_MARKER}\n### NikolAI review\n\n"
        "#### Checklist\n\n"
        "- [ ] **SQL built from input** · High · maintainability · "
        f"[src/db.py#L12]({PR_URL}/files#diff-{DB_PY}R12) · "
        f"[src/db.py#L40-L42]({PR_URL}/files#diff-{DB_PY}R40)"
        "<br>Use a parameterized query. "
        "<!-- nikolai:finding:00000000-0000-4000-8000-0000000000aa -->\n"
        "- [ ] **Unclear name** · Medium · maintainability · "
        f"[a.py#L1]({PR_URL}/files#diff-{A_PY}R1)"
        f"<br>Rename y. <!-- nikolai:finding:{FINDING_ID} -->\n\n"
        "_3 low-confidence findings were left out._\n\n"
        "#### Title and description\n\n"
        "The title is clear.\n\n"
        f"{FOOTER}"
    )


def test_markdown_html_mentions_and_links_in_a_finding_render_as_plain_text() -> None:
    hostile = item(
        "**Bold** <img src=x>",
        location("src/[x](y).py", 3),
        description="Line one.\n\n- [x] fake item @admin https://evil.example",
    )

    lines = comment(hostile).splitlines()

    assert lines[lines.index("#### Checklist") + 2 :][:2] == [
        "- [ ] **\\*\\*Bold\\*\\* &lt;img src=x&gt;** · Medium · maintainability · "
        f"[src/\\[x\\](y).py#L3]({PR_URL}/files#diff-{ODD_PY}R3)"
        "<br>Line one. - \\[x\\] fake item @&#8203;admin https\\://evil.example "
        f"<!-- nikolai:finding:{FINDING_ID} -->",
        "",
    ]


@pytest.mark.parametrize("description", ["# Heading", "1. ordered", "- nested", "---", "==="])
def test_a_description_that_starts_a_block_stays_inside_its_item(description: str) -> None:
    rendered = comment(item(description=description))

    assert f"maintainability · [a.py#L1]({PR_URL}/files#diff-{A_PY}R1)<br>{description} " in (
        rendered
    )


def test_an_item_without_lines_severity_category_or_description_still_names_its_file() -> None:
    bare = item(
        "Unclear name", location("a.py", None), description=None, severity=None, category=None
    )

    assert (
        f"- [ ] **Unclear name** · [a.py]({PR_URL}/files#diff-{A_PY}) "
        f"<!-- nikolai:finding:{FINDING_ID} -->\n"
    ) in comment(bare)


def test_one_withheld_finding_is_counted_in_the_singular() -> None:
    assert "_1 low-confidence finding was left out._" in comment(item(), withheld=1)


def test_a_review_with_no_findings_says_so() -> None:
    rendered = comment()

    assert (
        "#### Checklist\n\nNikolAI found no issues in the code changes.\n\n#### Title" in rendered
    )
    assert "- [ ]" not in rendered
    assert "left out" not in rendered


def test_a_review_whose_findings_were_all_withheld_says_none_were_confident() -> None:
    rendered = comment(withheld=3)

    assert (
        "#### Checklist\n\nNikolAI found no issues it is confident about in the code changes."
        "\n\n_3 low-confidence findings were left out._\n\n#### Title"
    ) in rendered


def test_a_review_with_nothing_to_send_the_model_says_so_instead_of_no_issues() -> None:
    rendered = comment(nothing_reviewed=True)

    assert (
        "#### Checklist\n\nNikolAI had no code changes to review: the changed files are "
        "generated, binary or too large to review.\n\n#### Title"
    ) in rendered
    assert "found no issues" not in rendered


def test_a_huge_checklist_fits_in_one_comment_and_drops_the_last_items_first() -> None:
    items = [item(f"Issue {n}", description="x" * 1_900) for n in range(100)]

    rendered = render_comment(
        review("y" * 30_000),
        PR_REF,
        CommentChecklist(checklist=Checklist(findings=items, withheld_count=0), failed_since=False),
    )

    assert len(rendered) <= MAX_COMMENT_CHARS
    listed = rendered.count("\n- [ ] ")
    assert 0 < listed < 100
    assert f"**Issue {listed - 1}**" in rendered
    assert f"**Issue {listed}**" not in rendered
    assert f"_{100 - listed} more findings are not listed, to fit in one comment._" in rendered
    # The title and description review keeps its reserved room, and the footer stays.
    assert "y" * 10_000 in rendered
    assert "_(review truncated)_" in rendered
    assert rendered.endswith(FOOTER)


@pytest.mark.parametrize(
    ("failed_since", "note"),
    [
        (False, "NikolAI hasn't reviewed the code changes yet."),
        (True, "NikolAI couldn't review the code changes this time."),
    ],
)
def test_without_any_checklist_the_comment_says_why(failed_since: bool, note: str) -> None:
    rendered = render_comment(
        review(), PR_REF, CommentChecklist(checklist=None, failed_since=failed_since)
    )

    assert f"#### Checklist\n\n{note}" in rendered
    assert "- [ ]" not in rendered
    assert rendered.endswith(FOOTER)


def test_a_checklist_no_failed_code_review_came_after_has_no_note() -> None:
    rendered = comment(item())

    assert "#### Checklist\n\n- [ ] **Unclear name**" in rendered


def test_a_checklist_a_failed_code_review_came_after_says_it_is_older() -> None:
    rendered = comment(item(), failed_since=True)

    assert (
        "#### Checklist\n\nNikolAI couldn't review the latest code changes, so this checklist is "
        "from an earlier review. It will try again when you push a new commit.\n\n- [ ] "
    ) in rendered


def test_a_review_that_was_not_saved_has_no_checklist_and_opens_the_ai_review() -> None:
    rendered = render_comment(review(), PR_REF)

    assert "#### Checklist" not in rendered
    assert "#### Title and description" not in rendered
    assert rendered.endswith(f"[Open in the NikolAI tab]({PR_URL}#nikolai/ai-review)</sub>")
