"""Render a NikolAI story review comment (US-12.1)."""

# AI contribution: 50%

from typing import Final, cast

from app.agents.story_review import CouldNotCheck, StoryCheckOutcome, StoryReviewResult
from app.github.comments import issue_url, nikolai_tab_link
from app.github.markdown import plain
from app.github.payloads import IssuesEvent

# First line of every NikolAI story comment, so a later check can find and edit it.
STORY_COMMENT_MARKER: Final = "<!-- nikolai:story-review -->"


def render_story_comment(outcome: StoryCheckOutcome, event: IssuesEvent) -> str:
    """The issue comment: the checks, the score, the suggested rewrite, and the footer."""
    footer = f"\n\n{_footer(event, outcome)}"
    body = (
        _checked_body(outcome.review)
        if outcome.review is not None
        else _could_not_check_body(cast("CouldNotCheck", outcome.reason))
    )
    return f"{STORY_COMMENT_MARKER}\n### NikolAI story review\n\n{body}{footer}"


# Every sentence is plain: an internal reason stays in the store and the log, and the
# comment names the problem the way a student reads it (the view #154 shows these too).
_COULD_NOT_CHECK_TEXT: Final[dict[CouldNotCheck, str]] = {
    CouldNotCheck.NOT_CONFIGURED: "NikolAI has no AI model configured right now.",
    CouldNotCheck.MODEL_UNAVAILABLE: "NikolAI's AI models are busy or unavailable.",
    CouldNotCheck.INVALID_REPLY: "The AI model's answer couldn't be used.",
    CouldNotCheck.INTERNAL_ERROR: "Something went wrong on NikolAI's side.",
}


def _could_not_check_body(reason: CouldNotCheck) -> str:
    return (
        f"NikolAI couldn't check this user story. {_COULD_NOT_CHECK_TEXT[reason]} "
        "It will try again when you edit the title or body."
    )


def _checked_body(review: StoryReviewResult) -> str:
    lines = [f"Score: **{review.score} / {review.max_score}**", ""]
    lines.extend(_check_line(item.passed, plain(item.text)) for item in review.checks)
    if review.current_text is None or review.suggested_text is None:
        return "\n".join(lines)
    lines.append("")
    lines.append("**Current**")
    lines.extend(_quoted(review.current_text).splitlines())
    lines.append("")
    lines.append("**Suggested rewrite**")
    lines.extend(_quoted(review.suggested_text).splitlines())
    return "\n".join(lines)


def _quoted(text: str) -> str:
    """Untrusted text as a blockquote, each line escaped so none can start a new block."""
    return "\n".join(f"> {plain(line)}" for line in text.splitlines() if line.strip())


def _check_line(passed: bool, text: str) -> str:
    mark = "✅" if passed else "❌"
    return f"- {mark} {text}"


def _footer(event: IssuesEvent, outcome: StoryCheckOutcome) -> str:
    """The AI-generated footer, shaped like every other NikolAI comment's (US-135).

    The Story card sits inline on issue pages (issues have no tab); the extension
    opens a view from the page's ``#nikolai/<view>`` hash (``nikolaiRoute`` in
    ``frontend/apps/extension/src/shared/page.ts``).
    """
    link = nikolai_tab_link(
        issue_url(event.repository.full_name, event.issue.number), "story-review"
    )
    if outcome.review is None:
        return f"<sub>AI-generated by NikolAI · {link}</sub>"
    return (
        f"<sub>AI-generated by NikolAI · {outcome.model} · "
        f"{(outcome.latency_ms or 0.0) / 1000:.1f} s · advisory feedback, not a grade · "
        f"{link}</sub>"
    )
